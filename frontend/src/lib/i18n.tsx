type Vars = Record<string, string | number>

function translate(lang: Lang, key: string, vars?: Vars): string {
  let raw = dict[lang][key] ?? dict.fr[key] ?? key
  if (raw.includes('|')) {
    const [one, many] = raw.split('|')
    const count = vars && 'count' in vars ? Number(vars.count) : 1
    raw = count > 1 ? many : one
  }
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      raw = raw.replace(new RegExp(`\\{${k}\\}`, 'g'), String(v))
    }
  }
  return raw
}

interface Ctx {
  lang: Lang
  setLang: (l: Lang) => void
  t: (key: string, vars?: Vars) => string
}

const LanguageContext = createContext<Ctx | null>(null)

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(() => {
    const stored = typeof localStorage !== 'undefined' ? localStorage.getItem(STORAGE_KEY) : null
    return stored === 'en' || stored === 'fr' ? stored : 'fr'
  })
  const setLang = useCallback((l: Lang) => {
    setLangState(l)
    try { localStorage.setItem(STORAGE_KEY, l) } catch { /* stockage indisponible */ }
  }, [])
  const t = useCallback((key: string, vars?: Vars) => translate(lang, key, vars), [lang])
  return (
    <LanguageContext.Provider value={{ lang, setLang, t }}>
      {children}
    </LanguageContext.Provider>
  )
}

// eslint-disable-next-line react-refresh/only-export-components
export function useI18n(): Ctx {
  const ctx = useContext(LanguageContext)
  if (!ctx) throw new Error('useI18n doit être utilisé dans un LanguageProvider')
  return ctx
}
